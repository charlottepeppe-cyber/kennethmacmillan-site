"""Apply the corrections listed in corrections.json, and drop photograph captions
that were also pasted into the running prose.

Everything this script changes is logged to CORRECTIONS.md so the edits made to
the archive are on the record rather than silently baked into the site.
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).parent
sys.path.insert(0, str(ROOT))
import facets

DATA = ROOT.parent / "site-data.json"
data = json.loads(DATA.read_text())
spec = json.loads((ROOT / "corrections.json").read_text())
rules = spec["replacements"]

log = []


def fix(text, where, field):
    if not text:
        return text
    for r in rules:
        if r["find"] in text:
            n = text.count(r["find"])
            text = text.replace(r["find"], r["replace"])
            log.append({"page": where, "field": field, "n": n,
                        "from": r["find"], "to": r["replace"], "note": r["note"]})
    return text


def norm(s):
    return re.sub(r"\W+", "", (s or "").lower())


pages = data["works"] + data["essays"]
dropped = []

for x in pages:
    where = x.get("name") or x.get("title")

    for i in x["images"]:
        i["caption"] = fix(i["caption"], where, "caption")
    for k in list(x.get("credits") or {}):
        x["credits"][k] = fix(x["credits"][k], where, f"credits/{k}")
    x["body"] = [fix(b, where, "body") for b in x["body"]]

    # a caption repeated verbatim in the prose reads as a stray fragment
    caps = {norm(i["caption"]) for i in x["images"] if i.get("caption")}
    caps.discard("")
    kept = []
    for b in x["body"]:
        if norm(b) in caps:
            dropped.append({"page": where, "text": b})
            continue
        kept.append(b)
    x["body"] = kept
    x["words"] = sum(len(b.split()) for b in x["body"])

# Some Squarespace asset names carry the same misspelling, and a filename shows
# in the URL. The download cache keeps the original names so it still mirrors the
# source; the published site gets corrected ones via this map.
renames = {}
for x in pages:
    for i in x["images"]:
        fn = i["file"]
        new = fn
        for r in rules:
            new = new.replace(r["find"].replace(" ", "-"), r["replace"].replace(" ", "-"))
        if new != fn:
            renames[fn] = new
data["image_renames"] = renames

# names inside credits feed the facets, so recompute them
for w in data["works"]:
    facets.derive(w)

DATA.write_text(json.dumps(data, indent=2, ensure_ascii=False))

# ---- the record ----
L = ["# Corrections to the archive text\n",
     "Generated by `extract/corrections.py`. The essays are otherwise reproduced "
     "exactly as written; these are the only changes made to the wording.\n",
     "## Spelling of proper names\n"]
if log:
    L.append("| Page | Where | Was | Now |")
    L.append("|---|---|---|---|")
    for e in log:
        L.append(f"| {e['page']} | {e['field']} | {e['from']} | {e['to']} |")
    L.append("\nReasons given in `extract/corrections.json`:\n")
    for r in rules:
        L.append(f"- **{r['find']}** to **{r['replace']}** — {r['note']}")
else:
    L.append("None outstanding.")

L.append(f"\n## Captions removed from running prose\n")
L.append(f"{len(dropped)} photograph captions had also been pasted into the body "
         "text of their page, where they read as stray fragments between "
         "paragraphs. They remain on the photographs themselves and were removed "
         "only from the prose.\n")
for e in dropped:
    L.append(f"- *{e['page']}* — {e['text'][:110]}")

(ROOT.parent / "CORRECTIONS.md").write_text("\n".join(L) + "\n")

print(f"name corrections applied: {sum(e['n'] for e in log)} in {len({e['page'] for e in log})} pages")
for e in log:
    print(f"   {e['page']}: {e['from']} -> {e['to']} ({e['field']})")
print(f"duplicate caption paragraphs removed: {len(dropped)} across "
      f"{len({d['page'] for d in dropped})} pages")
if renames:
    print(f"image files republished under corrected names: {len(renames)}")
    for a, b in renames.items():
        print(f"   {a}\n-> {b}")
