"""Coverage report: what the archive holds and where it is thin."""
import json, pathlib, collections

PROJ = pathlib.Path(__file__).parent.parent
d = json.loads((PROJ / "site-data.json").read_text())
W, E = d["works"], d["essays"]

L = []
a = L.append
a("# Archive coverage\n")
a("Regenerated by `site/report.py`. Gaps below are gaps in the source material, "
  "not in the build; nothing here has been filled in by guesswork.\n")

a(f"- **{len(W)} works**, {min(w['display_year'] for w in W)} to "
  f"{max(w['display_year'] for w in W)}")
a(f"- **{sum(w['words'] for w in W):,} words** of ballet notes, "
  f"**{sum(e['words'] for e in E):,}** across {len(E)} essays and information pages")
a(f"- **{sum(len(w['images']) for w in W)} photographs** placed on work pages, "
  f"{sum(len(e['images']) for e in E)} on essays")
a(f"- **{sum(1 for w in W if w['embeds'])} works** carry a video clip\n")

a("## Completeness by field\n")
a("| Field | Works | Missing |")
a("|---|---|---|")
for label, key in [("First performance", "premiere_raw"), ("Dated premiere", "premiere"),
                   ("Company", "company"), ("Cast", "cast"), ("Music", "music"),
                   ("Design", "design"), ("Benesh notation", "notation"),
                   ("Video record", "video"), ("Photograph", "images")]:
    n = sum(1 for w in W if w[key])
    a(f"| {label} | {n} | {len(W) - n} |")

a("\n## Recovered from the Internet Archive\n")
rec = [w for w in W if w.get("credits_source")]
a(f"{len(rec)} works had lost their credits entirely in the Squarespace migration "
  "and were restored from the pre-2016 site:\n")
for w in sorted(rec, key=lambda w: w["display_year"]):
    a(f"- {w['display_year']} **{w['name']}**")

a("\n## Works with no photograph\n")
noimg = [w for w in W if not w["images"]]
a(f"{len(noimg)} of {len(W)}. These are the pages that would gain most from the "
  "family or estate archive:\n")
for w in sorted(noimg, key=lambda w: w["display_year"]):
    a(f"- {w['display_year']} **{w['name']}** ({w['company'] or 'company not recorded'})")

thin = sorted([w for w in W if w["words"] < 260], key=lambda w: w["words"])
a(f"\n## Shortest entries\n\n{len(thin)} works have fewer than 260 words:\n")
for w in thin:
    a(f"- {w['words']:>3}w  {w['display_year']} **{w['name']}**")

a("\n## Most documented\n")
for k, label in [("company", "Companies"), ("designers", "Designers"), ("composers", "Composers")]:
    c = collections.Counter(x for w in W for x in
                            (w[k] if isinstance(w[k], list) else [w[k]]) if x)
    a(f"\n**{label}** ({len(c)} distinct)\n")
    for name, n in c.most_common(8):
        a(f"- {n} works: {name}")

(PROJ / "REPORT.md").write_text("\n".join(L) + "\n")
print(f"wrote REPORT.md ({len(L)} lines)")
print(f"  works without a photograph: {len(noimg)}")
print(f"  credits recovered from archive: {len(rec)}")
